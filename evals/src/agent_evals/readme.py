"""The README's eval table (8.5), generated from a run's summary.json. 0 requests.

    cd evals
    uv run python -m agent_evals.readme results/run-groq-full.summary.json          # rewrite
    uv run python -m agent_evals.readme results/run-groq-full.summary.json --check  # CI: stale?

Only the text between the two markers belongs to this script; the rest of the README is
hand-written and never touched. Running it twice changes nothing the second time.
"""

from __future__ import annotations

import argparse
from collections.abc import Sequence
from pathlib import Path

from agent_evals import summary as summary_mod
from agent_evals.summary import Counts, Summary

ROOT = Path(__file__).resolve().parents[3]  # evals/src/agent_evals/readme.py -> the repo
README = ROOT / "README.md"
START = "<!-- evals:start (generated by agent_evals.readme: don't edit by hand) -->"
END = "<!-- evals:end -->"


def pct(part: int, whole: int) -> str:
    return f"{part}/{whole} ({100 * part / whole:.0f} %)" if whole else "-"


def share(x: float | None) -> str:
    return f"{100 * x:.0f} %" if x is not None else "-"


def notes(s: Summary) -> list[str]:
    """The caveats a reader needs to trust the table: one sentence each, [] when none apply.

    The table shows what went well AND badly; the notes say what the numbers don't show on
    their own. A results table without its caveats is marketing, not measurement.
    """
    result: list[str] = []

    # 1. Partial evaluation
    if s.totals.n < s.suite_size:
        result.append(f"Partial run: {s.totals.n} of {s.suite_size} scenarios.")

    # 2. Errored scenarios
    if s.totals.errored > 0:
        result.append(
            f"{s.totals.errored} scenario(s) failed to complete; "
            "accuracy counts completed runs only."
        )

    # 3. Multiple diagnosing models
    if len(s.diagnosed_by) > 1:
        models = sorted(
            s.diagnosed_by.items(),
            key=lambda item: (-item[1], item[0]),
        )
        details = ", ".join(f"{model} {count}" for model, count in models)
        result.append(f"Multiple models contributed diagnoses: {details}.")

    # 4. Sensor drift misdiagnosed as a machine fault
    if s.blamed > 0:
        result.append(
            "Known weakness: sensor drift was blamed on the machine "
            f"in {pct(s.blamed, s.drifts)} of the drift scenarios."
        )

    # 5. LLM judge calibration
    if s.judge is not None:
        if s.judge.calibrated:
            result.append(
                "Root causes were double-checked by a calibrated "
                f"LLM judge, which agreed with the keyword grade "
                f"on {s.judge.agree} of {s.judge.judged} answers."
            )
        else:
            result.append(
                "LLM judge verdicts are not yet trusted because the judge has not been calibrated."
            )

    # 6. Stale evaluation results
    if s.stale > 0:
        result.append(
            f"{s.stale} stale scenario result(s) were detected; "
            "re-run them using the current setup."
        )

    return result


def _row(name: str, c: Counts) -> str:
    return f"| {name} | {c.n} | {c.correct} | {c.acceptable} | {c.wrong} | {c.errored} |"


def block(s: Summary, report: str) -> str:
    """The generated section (without the markers). `report`: link to the full report."""
    completed = s.totals.n - s.totals.errored
    traps = s.by_tag.get("trap")
    models = ", ".join(
        f"{m} ({n})" for m, n in sorted(s.diagnosed_by.items(), key=lambda kv: (-kv[1], kv[0]))
    )
    lines = [
        f"Run `{s.name}`: {s.totals.n} of {s.suite_size} scenarios"
        + (f", eval clock {s.eval_now:%Y-%m-%d %H:%M} UTC" if s.eval_now else "")
        + (f"; diagnosed by {models}" if models else "")
        + f". Full report: [{report}]({report}).",
        "",
        "| metric | result |",
        "|---|---|",
        f"| root-cause accuracy (correct / completed) | {pct(s.totals.correct, completed)} |",
        f"| completed | {pct(completed, s.totals.n)} |",
        f"| fault invented on a healthy machine | {pct(s.invented, s.controls)} |",
        f"| sensor drift blamed on the machine | {pct(s.blamed, s.drifts)} |",
    ]
    if traps:
        lines.append(f"| misleading-question traps | {pct(traps.correct, traps.n)} |")
    lines += [
        f"| citations valid (retrieved, not invented) | {share(s.citations_valid)} |",
        f"| citation recall (expected documents cited) | {share(s.citation_recall)} |",
        f"| expected tools called | {share(s.tools_ok)} |",
        f"| cost | {s.requests} requests, {s.tokens:,} tokens, "
        f"median {s.median_seconds:.0f} s per scenario |",
        "",
        "| fault | n | correct | acceptable | wrong | errored |",
        "|---|---|---|---|---|---|",
        *[_row(f, c) for f, c in s.by_fault.items() if f != "none"],
    ]
    if found := notes(s):
        lines += ["", *[f"- {n}" for n in found]]
    return "\n".join(lines)


def splice(text: str, generated: str) -> str:
    """`text` with the part between the markers replaced by `generated`."""
    start, end = text.find(START), text.find(END)
    if start < 0 or end < 0 or end < start:
        raise ValueError(f"README needs the two markers, in order:\n{START}\n{END}")
    return text[: start + len(START)] + "\n" + generated + "\n" + text[end:]


def report_link(summary_file: Path) -> str:
    """results/x.summary.json -> "evals/results/x.md", relative to the repo (README links)."""
    md = summary_file.resolve().with_name(summary_file.name.replace(".summary.json", ".md"))
    return md.relative_to(ROOT).as_posix()


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="agent_evals.readme", description=__doc__.split("\n")[0])
    parser.add_argument("summary_file", type=Path)
    parser.add_argument("--readme", type=Path, default=README)
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if the README is out of date, don't write"
    )
    args = parser.parse_args(argv)

    s = summary_mod.read(args.summary_file)
    old = args.readme.read_text(encoding="utf-8")
    new = splice(old, block(s, report_link(args.summary_file)))
    if args.check:
        print("README up to date" if new == old else f"README out of date: re-run {parser.prog}")
        return 0 if new == old else 1
    args.readme.write_text(new, encoding="utf-8", newline="\n")
    print(f"{'unchanged' if new == old else 'updated'}: {args.readme}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
