DRIFT_KEYWORDS = [
    ["sensor", "transmitter", "rtd", "probe", "measurement"],
    ["drift", "calibrat", "faulty", "false", "offset"],
]
DRIFT_QUESTIONS = [
    "{alarm} alarm on {machine} ({sensor}). What is wrong with the machine?",
    "{sensor} on {machine} has been rising for two days. Should we stop the machine?",
]
# Two sensors of DIFFERENT kinds per machine type. The dp sensors are deliberate traps: a
# drifting dp reads like a clogged filter, but nothing else on the machine moves.
# (M-08 discharge_temp is the hand-written sensor-drift-m08.)
DRIFT_SENSORS: list[tuple[str, str]] = [
    ("M-02", "spindle_bearing_temp"),
    ("M-03", "coolant_pressure"),
    ("M-05", "hydraulic_oil_temp"),
    ("M-06", "hydraulic_pressure"),
    ("M-04", "drive_motor_temp"),
    ("M-07", "gearbox_vibration"),
    ("M-08", "inlet_filter_dp"),
    ("M-08", "motor_vibration"),
    ("M-09", "suction_strainer_dp"),
    ("M-09", "bearing_temp"),
]
CONTROL_QUESTIONS = [
    "Quick health check on {machine} before the weekend: any concerns?",
    "Anything unusual on {machine} in the last few days?",
]


@dataclass(frozen=True)
class Variant:
    name: str  # typical | mild | advanced (also its tag)
    severity: float
    may_be_weak: bool  # 'unknown' accepted if the fault's weak_mild says so


# Severity, not duration: a scenario's fault is fully developed when the question is asked
# (start = now - duration), so what varies is how strong it got. Note motor_overload: at
# severity >= 1.0 the overload relay trips (the machine is DOWN), below it only struggles.
VARIANTS = [
    Variant("typical", 1.0, may_be_weak=False),
    Variant("mild", 0.5, may_be_weak=True),
    Variant("advanced", 1.5, may_be_weak=False),
]
MILD_NOTES = (
    "Mild (severity 0.5) and weak: no alarm in the dry run, only the readings show it, so "
    "'unknown' is an honest answer here. A confident wrong diagnosis is still a failure."
)


def _id(*parts: str) -> str:
    """gen-sensor-drift-m08-motor-vibration: machine codes as m08, like the hand-written ids."""
    return PREFIX + "-".join(p.lower().replace("m-", "m", 1).replace("_", "-") for p in parts)


def _machines_by_type(plant: PlantConfig) -> dict[MachineType, list[str]]:
    by_type: dict[MachineType, list[str]] = {}
    for m in sorted(plant.machines, key=lambda m: m.code):
        by_type.setdefault(m.type, []).append(m.code)
    return by_type


def _fault_scenarios(plant: PlantConfig) -> list[dict[str, Any]]:
    by_type = _machines_by_type(plant)
    out: list[dict[str, Any]] = []
    for fault, know in FAULT_KNOWLEDGE.items():
        types = sorted(APPLICABLE[fault])
        for j, mtype in enumerate(types):
            machines = by_type[mtype]
            for i, v in enumerate(VARIANTS):
                machine = machines[i % len(machines)]  # spread over the machines of that type
                question = know.questions[(i + j) % len(know.questions)]
                tags = ["generated", v.name]
                if j == 0 and v.name == "typical":
                    tags.insert(0, "smoke")  # one per fault family
                allow_unknown = v.may_be_weak and mtype in know.weak_mild
                category = ["machine_fault", "unknown"] if allow_unknown else ["machine_fault"]
                scenario: dict[str, Any] = {
                    "id": _id(fault, mtype, v.name),
                    "description": f"{fault} on a {mtype} ({machine}), {v.name} "
                    f"(severity {v.severity}).",
                    "setup": {"machine": machine, "fault": str(fault), "severity": v.severity},
                    "question": question.format(machine=machine),
                    "expect": {
                        "category": category,
                        "root_cause_keywords": know.keywords,
                        "must_cite": know.cite[mtype],
                        "work_order": "optional" if allow_unknown else "required",
                    },
                    "tags": tags,
                }
                if allow_unknown:
                    scenario["notes"] = MILD_NOTES
                out.append(scenario)
    return out


def _drift_scenarios(plant: PlantConfig) -> list[dict[str, Any]]:
    sensors = {
        (m.code, s.name): s.kind for m in plant.machines for s in plant.sensor_templates[m.type]
    }
    out: list[dict[str, Any]] = []
    for i, (machine, sensor) in enumerate(DRIFT_SENSORS):
        kind: SensorKind = sensors[(machine, sensor)]
        question = DRIFT_QUESTIONS[i % len(DRIFT_QUESTIONS)]
        out.append(
            {
                "id": _id("sensor-drift", machine, sensor),
                "description": f"{sensor} on {machine} drifts upwards; every other signal of "
                "the machine stays normal.",
                "setup": {"machine": machine, "fault": "sensor_drift", "sensor": sensor},
                "question": question.format(
                    machine=machine, sensor=sensor, alarm=f"{KIND_CODE[kind]}-HIGH"
                ),
                "expect": {
                    "category": ["sensor_fault"],
                    "root_cause_keywords": DRIFT_KEYWORDS,
                    "must_cite": [VERIFICATION_SOP],
                    "work_order": "optional",
                },
                "tags": ["generated", "drift"],
            }
        )
    return out


def _control_scenarios(plant: PlantConfig) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for i, (mtype, machines) in enumerate(sorted(_machines_by_type(plant).items())):
        machine = machines[0]  # (the hand-written control-m10 covers a second conveyor)
        out.append(
            {
                "id": _id("control", mtype, machine),
                "description": f"Healthy {mtype} ({machine}), nothing injected: the agent "
                "must not invent a problem.",
                "setup": {"machine": machine},
                "question": CONTROL_QUESTIONS[i % len(CONTROL_QUESTIONS)].format(machine=machine),
                "expect": {"category": ["no_fault", "unknown"], "work_order": "forbidden"},
                "tags": ["generated", "control"],
            }
        )
    return out


class _Dumper(yaml.SafeDumper):
    """Lists of plain values on one line ([a, b]), like the hand-written files: readable."""


def _represent_list(dumper: yaml.SafeDumper, data: list[Any]) -> yaml.Node:
    flat = all(not isinstance(x, dict) for x in data)
    return dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=flat)


_Dumper.add_representer(list, _represent_list)


def render(plant: PlantConfig) -> dict[str, str]:
    """file name -> file content, for every generated scenario. Pure: writes nothing."""
    files: dict[str, str] = {}
    for raw in _fault_scenarios(plant) + _drift_scenarios(plant) + _control_scenarios(plant):
        Scenario.model_validate(raw)  # fail here, with the generator in the traceback
        # a SafeDumper quotes strings YAML would misread ('false', 'no'): no Norway problem
        body = yaml.dump(raw, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100)
        files[f"{raw['id']}.yaml"] = HEADER + body
    return files


def write(directory: Path, files: dict[str, str]) -> tuple[int, int]:
    """Write `files`, delete generated files that are no longer produced. (written, deleted)"""
    stale = [p for p in directory.glob(f"{PREFIX}*.yaml") if p.name not in files]
    for p in stale:
        p.unlink()
    for name, text in files.items():
        # newline="\n": the same bytes on Windows and in CI (like openapi.json)
        (directory / name).write_text(text, encoding="utf-8", newline="\n")
    return len(files), len(stale)


def main() -> None:
    written, deleted = write(SCENARIOS, render(load_plant(get_settings().plant_file)))
    print(f"wrote {written} generated scenarios to {SCENARIOS}, deleted {deleted} stale ones")


if __name__ == "__main__":
    main()
